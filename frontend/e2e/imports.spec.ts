test('timeline loads more without duplicates and reloads after archive changes',async ({page,request}) => {
  const mapping=Object.fromEntries(['conversation_id','sender_id','sent_at','message_id','body'].map(key=>[key,key]));
  const add=async(count:number,namespace:string)=>{
    const rows=Array.from({length:count},(_,index)=>({conversation_id:'group-1',sender_id:'merchant-a',sent_at:'2026-11-12T12:00:00+08:00',message_id:`row-${index}`,body:`分页原文${index}`}));
    const preview=await (await request.post('/api/imports',{data:{mode:'preview',account_id:'acct-1',namespace,format:'json',mapping,content:JSON.stringify(rows)}})).json();
    expect(preview.counts.valid).toBe(count);
    expect((await request.post('/api/imports',{data:{mode:'commit',account_id:'acct-1',preview_id:preview.preview_id}})).ok()).toBeTruthy();
  };
  await add(55,'pages');
  await page.getByRole('button',{name:'查看 商家甲',exact:true}).click();
  const detail=page.getByRole('dialog');
  await detail.getByRole('tab',{name:'沟通原文',exact:true}).click();
  await expect(detail.locator('[data-message]')).toHaveCount(50);
  await add(1,'new-revision');
  await detail.getByRole('button',{name:'加载更多原文',exact:true}).click();
  await expect(detail.getByRole('alert')).toContainText('原文已更新');
  await detail.getByRole('button',{name:'重新加载原文',exact:true}).click();
  await expect(detail.getByText('60 条原文',{exact:true})).toBeVisible();
  await detail.getByRole('button',{name:'加载更多原文',exact:true}).click();
  await expect(detail.locator('[data-message]')).toHaveCount(60);
  const ids=await detail.locator('[data-message]').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('data-message')));
  expect(new Set(ids).size).toBe(60);
});
