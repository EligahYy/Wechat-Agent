const {chromium}=require('playwright');
const http=require('http');
const fs=require('fs');
const path=require('path');
(async()=>{
 const server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html; charset=utf-8');res.end(fs.readFileSync(path.resolve('docs/UI_PROTOTYPE.html')))});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));server.unref();
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`http://127.0.0.1:${server.address().port}`);
 await page.getByRole('button',{name:'查看并处理'}).first().click();
 await page.getByRole('button',{name:'标记这件事已处理'}).click();
 if(await page.locator('.cards .card').count()!==1)throw Error('completion');
 await page.getByRole('button',{name:'撤销',exact:true}).click();
 if(await page.locator('.cards .card').count()!==2)throw Error('undo');
 await page.getByRole('tab',{name:'待确认'}).click();
 await page.getByRole('button',{name:'查看并确认'}).click();
 await page.getByRole('button',{name:'保存判断'}).click();
 if(!await page.locator('#detail-status').textContent())throw Error('inline validation');
 await page.locator('#batch').selectOption({label:'德国第二批'});
 await page.getByRole('button',{name:'保存判断'}).click();
 if(await page.locator('.cards .card').count())throw Error('review not resolved');
 await page.getByRole('button',{name:'客户',exact:true}).click();
 await page.getByRole('textbox',{name:'搜索客户'}).fill('不存在');
 await page.getByRole('button',{name:'清除搜索'}).click();
 await page.getByRole('button',{name:'数据',exact:true}).click();
 if(await page.locator('.list .row').count()!==50)throw Error('page size');
 await page.getByRole('button',{name:'下一页'}).click();
 if(await page.locator('.list .row').count()!==3)throw Error('pagination');
 await page.getByRole('tab',{name:'免跟进',exact:true}).click();
 if(await page.locator('[data-source]').filter({hasText:'免跟进'}).count())throw Error('wrong exemption button');
 await page.getByRole('button',{name:'恢复处理'}).first().click();
 await page.getByRole('button',{name:'撤销',exact:true}).click();
 await page.getByRole('button',{name:'今日',exact:true}).click();
 await page.getByRole('tab',{name:'该联系'}).click();
 await page.screenshot({path:'/tmp/wechat-design-desktop.png',fullPage:true,animations:'disabled'});
 await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
 await page.setViewportSize({width:320,height:800});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('mobile overflow');
 await page.getByRole('button',{name:'查看并处理'}).first().click();
 await page.keyboard.press('Escape');
 if(await page.locator('dialog').isVisible())throw Error('escape');
 await page.screenshot({path:'/tmp/wechat-design-mobile.png',fullPage:true,animations:'disabled'});
 if(errors.length)throw Error(errors.join('\n'));
 await browser.close();server.close();console.log('Design interactions, pagination, mobile, dark mode and reduced motion passed.');
})().catch(e=>{console.error(e);process.exit(1)});
